<?php
/* ==========================================================================
   DYNAMIC SONG DATA (songs-data.php)
   Serves the same JavaScript contract as assets/js/songs-data.js:

       const AF_SONGS = [ {t,a,l,i,s,d,c}, ... ];
       const AF_LANGS = ["All", ...];

   ...but the values come from the `songs` table, so anything an editor adds or
   changes in the admin panel shows up on Music / Album / home immediately.
   When the database has no music rows (or MySQL is down) the original static
   file is served verbatim, so the site never looks different.

   Referenced as <script src="songs-data.php"> by music.php, album.php and
   index.php. Cached for 60 seconds; bust with ?v=<anything>.
   ========================================================================== */

require_once __DIR__ . '/includes/content.php';

/* the shared file is the fallback + the language seed */
$staticFile = __DIR__ . '/assets/js/songs-data.js';
$static     = (is_file($staticFile) && ($c = @file_get_contents($staticFile)) !== false) ? $c : '';

$music = af_music_songs_js();
$langs = af_languages_js();

header('Content-Type: application/javascript; charset=utf-8');
header('X-Content-Type-Options: nosniff');
header('Cache-Control: public, max-age=60');

if (!$music) {
    /* no DB rows -> the original file, unchanged */
    echo $static;
    exit;
}

/* JS string encoding that keeps unicode readable and quotes safe */
function sj($value)
{
    $json = json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    return $json === false ? '""' : $json;
}

echo "/* Generated by songs-data.php on " . date('Y-m-d H:i:s') . " - edit these in the Admin panel. */\n";
echo 'const AF_SONGS = [' . "\n";
$lines = [];
foreach ($music as $s) {
    $lines[] = '  {"t":' . sj($s['t'])
             . ',"a":' . sj($s['a'])
             . ',"l":' . sj($s['l'])
             . ',"i":' . sj($s['i'])
             . ',"s":' . sj($s['s'])
             . ',"d":' . (int) $s['d']
             . ',"c":' . sj($s['c']) . '}';
}
echo implode(",\n", $lines) . "\n];\n\n";
echo 'const AF_LANGS = ' . sj($langs) . ";\n";
